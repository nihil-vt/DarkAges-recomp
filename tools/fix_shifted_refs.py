#!/usr/bin/env python3
"""Find references that are 0xC00 bytes off inside the game's old-build code.

A few functions in this ROM (the entry stub, the engine init and 24 switch
statements) were built for a ROM layout that is 0xC00 bytes smaller, so their
absolute references into the code section point 0xC00 bytes too low. Their
references into the boot section (0x8000xxxx) are unaffected.

This script prints N64Recomp instruction patches for the affected `jal`
instructions.
"""

import struct
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from fix_symbols import parse  # noqa: E402

DELTA = 0xC00
ROOT = Path(__file__).resolve().parent.parent
ROM = ROOT / "roms" / "Mace - The Dark Age (USA).z64"

# Functions that were built for the old (0xC00 smaller) layout.
OLD_BUILD_FUNCS = ["func_8006cb64", "recomp_entrypoint"]


def jal_word(target, pc):
    imm = ((target - (pc & 0xF0000000)) >> 2) & 0x03FFFFFF
    return (3 << 26) | imm


def main():
    sections = parse(ROOT / "config" / "symbols.toml")
    rom = ROM.read_bytes()

    starts = {}
    for sec in sections:
        for name, vram, size in sec.funcs:
            starts.setdefault(vram, name)

    print("# References that are 0xC00 bytes off (old build) - generated by")
    print("# tools/fix_shifted_refs.py")
    for func_name in OLD_BUILD_FUNCS:
        for sec in sections:
            for name, vram, size in sec.funcs:
                if name != func_name:
                    continue
                base = vram - 0x80000000
                for off in range(base, base + size, 4):
                    word = struct.unpack_from(">I", rom, off)[0]
                    if word >> 26 != 3:
                        continue
                    target = 0x80000000 | (((word & 0x03FFFFFF) << 2) & 0x0FFFFFFF)
                    shifted = target + DELTA
                    # Only patch references into the code section, and only
                    # when the shifted address is a known function.
                    if target < 0x80010000 or shifted not in starts:
                        continue
                    vram = 0x80000000 + off
                    print("[[patches.instruction]]")
                    print(f'func = "{name}"')
                    print(f"vram = 0x{vram:08X}")
                    print(f"value = 0x{jal_word(shifted, vram):08X}")
                    print(f"# 0x{target:08X} -> 0x{shifted:08X} ({starts[shifted]})")


if __name__ == "__main__":
    main()
