#!/usr/bin/env python3
"""Regenerate config/symbols.toml from the raw Ghidra function list.

The Ghidra export was produced from a flat load at 0x80000000, but the
cart's code section (0x1000) actually runs at 0x80000400 (the ROM header's
entry point). Every Ghidra address is therefore 0xC00 too high.

The IPL3 at cart 0x400..0x1000 is not game code -- the N64 boot code drives
the PI hardware directly and the runtime replaces it -- so it is dropped.
"""

import json
import re
import sys
from pathlib import Path

# Cart 0x1000 is the game's code section; it runs at 0x80000400.
CODE_ROM = 0x1000
CODE_VRAM = 0x80000400
CODE_SIZE = 0x7D600 - CODE_ROM

# Ghidra loaded flat at 0x80000000.
GHIDRA_BASE = 0x80000000
SHIFT = GHIDRA_BASE - CODE_VRAM  # 0xC00


def main():
    json_path = Path(sys.argv[1])
    out_path = Path(sys.argv[2])
    funcs = json.loads(re.sub(r",\s*]", "]", json_path.read_text()))

    out = [
        "# Auto-generated by tools/json_to_toml.py -- do not edit.",
        "#",
        "# Ghidra addresses are 0xC00 too high (flat load at 0x80000000).",
        "# Cart 0x1000 maps to 0x80000400 (ROM header entry point).",
        "",
        "[[section]]",
        'name = "code"',
        f"rom = 0x{CODE_ROM:x}",
        f"vram = 0x{CODE_VRAM:x}",
        f"size = 0x{CODE_SIZE:x}",
    ]
    for func in funcs:
        vram = func["vram"] - SHIFT
        if not (CODE_VRAM <= vram < CODE_VRAM + CODE_SIZE):
            continue
        out += [
            "",
            "[[section.functions]]",
            f'name = "func_{vram:08x}"',
            f"vram = 0x{vram:x}",
            f"size = 0x{func['size']:x}",
        ]
    out.append("")
    out_path.write_text("\n".join(out) + "\n")
    print(f"wrote {out_path} with {len(funcs)} source functions")


if __name__ == "__main__":
    main()