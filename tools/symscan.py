#!/usr/bin/env python3
"""Mace N64 function boundary scanner -> N64Recomp symbol TOML.

Heuristic (IDO-built code):
 1. text starts at ROM 0x1000 (vaddr 0x80001000)
 2. text end = first sustained block with no jal/jr/branch (data/rodata follows)
 3. function starts = jal targets inside text (+ text base)
 4. functions tile [start, next_start); validate each has a `jr ra`
"""
import struct, sys
from capstone import Cs, CS_ARCH_MIPS, CS_MODE_MIPS32, CS_MODE_BIG_ENDIAN

ROM = sys.argv[1] if len(sys.argv) > 1 else 'roms/Mace - The Dark Age (USA).z64'
OUT = sys.argv[2] if len(sys.argv) > 2 else 'config/symbols.toml'

data = open(ROM, 'rb').read()
TEXT_ROM = 0x1000
TEXT_VRAM = 0x80001000
md = Cs(CS_ARCH_MIPS, CS_MODE_MIPS32 | CS_MODE_BIG_ENDIAN)
md.detail = False

def words(off, n):
    return struct.unpack('>%dI' % n, data[off:off + n * 4])

# --- 1. text end: block scan for control-flow density
BLOCK = 0x100
last_cf = None
text_end = None
start_scan = TEXT_ROM
# precompute: does block contain jal(3) / jr(special,funct=8) / branch(1,4,5,6,7,20-23)
def cf_count(off, size):
    cnt = 0
    for w in words(off, size // 4):
        op = w >> 26
        if op == 3 or op in (1, 4, 5, 6, 7, 20, 21, 22, 23):
            cnt += 1
        elif op == 0 and (w & 0x3F) in (8, 9):  # jr / jalr
            cnt += 1
    return cnt

i = TEXT_ROM
quiet_run = 0
while i + BLOCK <= len(data):
    c = cf_count(i, BLOCK)
    if c == 0:
        quiet_run += 1
        if quiet_run >= 8:  # 2KB sustained silence -> not code
            text_end = i - 7 * BLOCK
            break
    else:
        quiet_run = 0
    i += BLOCK
if text_end is None:
    text_end = 0x80000  # fallback guess
text_end &= ~0xF
print(f"text: {TEXT_ROM:#x}..{text_end:#x} ({text_end - TEXT_ROM} bytes)")

# --- 2. jal targets
starts = set([TEXT_VRAM])
for off in range(TEXT_ROM, text_end, 4):
    w = data[off] << 24 | data[off + 1] << 16 | data[off + 2] << 8 | data[off + 3]
    if (w >> 26) == 3:
        pc = TEXT_VRAM + (off - TEXT_ROM)
        tgt = ((pc + 4) & 0xF0000000) | ((w & 0x03FFFFFF) << 2)
        if TEXT_VRAM <= tgt < TEXT_VRAM + (text_end - TEXT_ROM) and (tgt & 3) == 0:
            starts.add(tgt)
starts = sorted(starts)
print(f"function starts: {len(starts)}")

# --- 3. validate + emit
funcs = []
no_jr = 0
for idx, s in enumerate(starts):
    e = starts[idx + 1] if idx + 1 < len(starts) else TEXT_VRAM + (text_end - TEXT_ROM)
    size = e - s
    rom_off = TEXT_ROM + (s - TEXT_VRAM)
    ws = words(rom_off, size // 4)
    has_jr = any((w >> 26) == 0 and (w & 0x3F) == 8 for w in ws)
    if not has_jr:
        no_jr += 1
    funcs.append((s, size, has_jr))

print(f"functions without jr ra: {no_jr}")

with open(OUT, 'w') as f:
    f.write(f'''# Auto-generated by tools/symscan.py — do not edit by hand.
[[section]]
name = "code"
rom = {TEXT_ROM:#x}
vram = {TEXT_VRAM:#x}
size = {text_end - TEXT_ROM:#x}

''')
    for s, size, has_jr in funcs:
        suffix = '' if has_jr else '  # NO jr ra - suspect'
        f.write(f'[[section.functions]]\nname = "func_{s:08x}"\nvram = {s:#010x}\nsize = {size:#x}{suffix}\n\n')
print(f"wrote {OUT}")
